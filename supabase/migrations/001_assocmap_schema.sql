-- 01. roles
CREATE TABLE public.roles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50) NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL UNIQUE,
    description     TEXT,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 02. user_profiles
-- auth.users owns email/password/authentication.
CREATE TABLE public.user_profiles (
    id              UUID PRIMARY KEY
                    REFERENCES auth.users(id) ON DELETE CASCADE,
    role_id         BIGINT NOT NULL
                    REFERENCES public.roles(id) ON DELETE RESTRICT,
    display_name    VARCHAR(255) NOT NULL,
    contact_number  VARCHAR(30),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    invited_by      UUID
                    REFERENCES public.user_profiles(id) ON DELETE SET NULL,
    invited_at      TIMESTAMPTZ,
    activated_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 03. email_change_requests
CREATE TABLE public.email_change_requests (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL
                    REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    old_email       VARCHAR(255) NOT NULL,
    new_email       VARCHAR(255) NOT NULL,
    requested_by    UUID
                    REFERENCES public.user_profiles(id) ON DELETE SET NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','confirmed','cancelled','expired')),
    confirmed_at    TIMESTAMPTZ,
    cancelled_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (LOWER(old_email) <> LOWER(new_email)),
    CHECK (
        (status = 'confirmed' AND confirmed_at IS NOT NULL)
        OR status <> 'confirmed'
    )
);

CREATE UNIQUE INDEX uq_email_change_pending_per_user
ON public.email_change_requests(user_id)
WHERE status = 'pending';

