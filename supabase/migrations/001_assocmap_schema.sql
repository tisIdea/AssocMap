-- 14. member_applications
CREATE TABLE public.member_applications (
    id                          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    association_id              UUID NOT NULL
                                REFERENCES public.associations(id) ON DELETE RESTRICT,
    submitted_by_user_id        UUID NOT NULL
                                REFERENCES public.user_profiles(id) ON DELETE RESTRICT,
    first_name                  VARCHAR(120) NOT NULL,
    middle_name                 VARCHAR(120),
    last_name                   VARCHAR(120) NOT NULL,
    suffix                      VARCHAR(20),
    birth_date                  DATE NOT NULL,
    sex_id                      BIGINT NOT NULL
                                REFERENCES public.sex_categories(id) ON DELETE RESTRICT,
    contact_number              VARCHAR(30),
    fishr_registration_number   VARCHAR(100),
    position_id                 BIGINT NOT NULL
                                REFERENCES public.association_positions(id) ON DELETE RESTRICT,
    position_other_text         VARCHAR(100),
    status                      VARCHAR(20) NOT NULL DEFAULT 'pending'
                                CHECK (status IN ('pending','approved','rejected')),
    reviewed_by                 UUID
                                REFERENCES public.user_profiles(id) ON DELETE SET NULL,
    reviewed_at                 TIMESTAMPTZ,
    rejection_reason            TEXT,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (birth_date <= CURRENT_DATE),
    CHECK (
        (status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL)
        OR
        (status = 'approved' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL)
        OR
        (status = 'rejected' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL AND BTRIM(rejection_reason) <> '')
    )
);

CREATE UNIQUE INDEX uq_pending_or_approved_application_fishr
ON public.member_applications (fishr_registration_number)
WHERE fishr_registration_number IS NOT NULL
  AND status IN ('pending','approved');

