-- Monitoring Income must use one frequency per production row and monthly month must fall in parent quarter.
CREATE OR REPLACE FUNCTION public.validate_monitoring_income_period()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    q SMALLINT;
    min_month SMALLINT;
    max_month SMALLINT;
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.monitoring_income mi
        WHERE mi.monitoring_production_id = NEW.monitoring_production_id
          AND mi.id <> NEW.id
          AND mi.period_type <> NEW.period_type
    ) THEN
        RAISE EXCEPTION 'Income for one production row must use either monthly or quarterly entries, not both.';
    END IF;

    IF NEW.period_type = 'monthly' THEN
        SELECT qtr.quarter_number
        INTO q
        FROM public.monitoring_production mp
        JOIN public.monitoring_records mr ON mr.id = mp.monitoring_record_id
        JOIN public.quarters qtr ON qtr.id = mr.quarter_id
        WHERE mp.id = NEW.monitoring_production_id;

        min_month := ((q - 1) * 3) + 1;
        max_month := min_month + 2;

        IF NEW.month < min_month OR NEW.month > max_month THEN
            RAISE EXCEPTION 'Monthly gross income month must fall within the monitoring record quarter.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

