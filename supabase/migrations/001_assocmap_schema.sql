AS $$
DECLARE
    geom_type TEXT;
BEGIN
    geom_type := ST_GeometryType(NEW.geom);

    IF NEW.location_type = 'association_point' THEN
        IF NEW.association_id IS NULL OR NEW.project_id IS NOT NULL OR geom_type <> 'ST_Point' THEN
            RAISE EXCEPTION 'association_point requires an Association parent and POINT geometry.';
        END IF;
    ELSIF NEW.location_type = 'project_point' THEN
        IF NEW.project_id IS NULL OR NEW.association_id IS NOT NULL OR geom_type <> 'ST_Point' THEN
            RAISE EXCEPTION 'project_point requires a Project parent and POINT geometry.';
        END IF;
    ELSIF NEW.location_type = 'project_boundary' THEN
        IF NEW.project_id IS NULL OR NEW.association_id IS NOT NULL OR geom_type NOT IN ('ST_Polygon','ST_MultiPolygon') THEN
            RAISE EXCEPTION 'project_boundary requires a Project parent and POLYGON or MULTIPOLYGON geometry.';
        END IF;
    END IF;

    IF ST_SRID(NEW.geom) <> 4326 THEN
        RAISE EXCEPTION 'GIS geometry must use SRID 4326 (WGS84).';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_gis_location
BEFORE INSERT OR UPDATE OF association_id, project_id, location_type, geom
ON public.gis_locations
FOR EACH ROW
EXECUTE FUNCTION public.validate_gis_location();

